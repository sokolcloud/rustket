//! E2E payloads captured from the dev server (`tests/fixtures/e2e/`, written by
//! `rustket-core/tests/e2e_live.rs` with `RUSTKET_CAPTURE_E2E_FIXTURES=1`).

#![allow(clippy::unwrap_used)]

use rocketchat::e2e::{EncryptedContent, UserPublicKey, WrappedKey};
use rocketchat::models::{Message, Room, Subscription};
use rocketchat::rest::MyKeys;
use serde_json::Value;

fn fixture(name: &str) -> Value {
    let path = format!("{}/tests/fixtures/e2e/{name}", env!("CARGO_MANIFEST_DIR"));
    serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap()
}

#[test]
fn fetch_my_keys() {
    let keys: MyKeys = serde_json::from_value(fixture("fetch_my_keys.json")).unwrap();
    assert!(keys.has_keys());
    UserPublicKey::from_jwk_str(keys.public_key.as_deref().unwrap()).unwrap();
    let env: Value = serde_json::from_str(keys.private_key.as_deref().unwrap()).unwrap();
    assert_eq!(env["iterations"], 100_000);
    assert!(env["salt"].as_str().unwrap().starts_with("v2:"));
}

#[test]
fn users_without_key() {
    let v = fixture("get_users_of_room_without_key.json");
    let users = v["users"].as_array().unwrap();
    assert!(!users.is_empty());
    for u in users {
        UserPublicKey::from_jwk_str(u["e2e"]["public_key"].as_str().unwrap()).unwrap();
    }
}

#[test]
fn room_and_subscriptions() {
    let room: Room =
        serde_json::from_value(fixture("rooms_info_e2e.json")["room"].clone()).unwrap();
    assert_eq!(room.encrypted, Some(true));
    let kid = room.e2e_key_id.clone().unwrap();
    let last = room.last_message.unwrap();
    let Some(Ok(EncryptedContent::V2 {
        kid: msg_kid, iv, ..
    })) = last.encrypted_content()
    else {
        panic!("last message is not a v2 envelope")
    };
    assert_eq!(msg_kid, kid);
    assert_eq!(iv.len(), 12);

    let sub: Subscription = serde_json::from_value(
        fixture("subscriptions_get_one_suggested.json")["subscription"].clone(),
    )
    .unwrap();
    let w = WrappedKey::parse(sub.e2e_suggested_key.as_deref().unwrap()).unwrap();
    assert_eq!(w.kid, kid);
    assert_eq!(sub.e2e_suggested_key.unwrap().len(), 36 + 344);

    let after: Subscription =
        serde_json::from_value(fixture("subscription_after_reset.json")["subscription"].clone())
            .unwrap();
    let old = after.old_room_keys.unwrap();
    assert!(!old.is_empty());
    assert!(old[0].ts.is_some());
    let w = WrappedKey::parse(&old[0].e2e_key).unwrap();
    assert_eq!(w.kid, old[0].e2e_key_id);
    assert_ne!(
        WrappedKey::parse(after.e2e_key.as_deref().unwrap())
            .unwrap()
            .kid,
        old[0].e2e_key_id
    );
}

#[test]
fn encrypted_messages() {
    let m: Message =
        serde_json::from_value(fixture("chat_get_message_e2e.json")["message"].clone()).unwrap();
    assert_eq!(m.t.as_deref(), Some("e2e"));
    assert_eq!(m.msg, "");
    assert!(m.md.is_none());
    assert!(m.is_encrypted() && !m.is_system());
    assert!(
        !m.e2e_mentions
            .as_ref()
            .unwrap()
            .e2e_user_mentions
            .is_empty()
    );
    assert!(matches!(
        m.encrypted_content(),
        Some(Ok(EncryptedContent::V2 { .. }))
    ));

    let up: Message =
        serde_json::from_value(fixture("chat_get_message_e2e_upload.json")["message"].clone())
            .unwrap();
    assert!(matches!(
        up.encrypted_content(),
        Some(Ok(EncryptedContent::V2 { .. }))
    ));
    // The server-side attachment only knows the hashed name.
    let att = &up.attachments.as_ref().unwrap()[0];
    assert_eq!(att.title.as_deref().map(str::len), Some(64));
    assert!(att.encryption.is_none());
    assert_eq!(
        up.file.as_ref().unwrap().mime.as_deref(),
        Some("application/octet-stream")
    );

    let pin: Message =
        serde_json::from_value(fixture("message_pinned_e2e.json")["message"].clone()).unwrap();
    assert_eq!(pin.t.as_deref(), Some("message_pinned_e2e"));
    assert!(pin.encrypted_content().is_none());
    let content = pin.attachments.as_ref().unwrap()[0]
        .content
        .as_ref()
        .unwrap();
    assert!(matches!(
        EncryptedContent::from_value(content),
        Ok(EncryptedContent::V2 { .. })
    ));
}

/// Keys generated by Rustket, imported by Node 24 WebCrypto (the browser API,
/// with its JWK import rules), which wrapped a room key, encrypted a message and
/// a key backup the way the web client does (fixture made once, see `docs/e2e.md`
/// §15).
#[test]
fn webcrypto_interop() {
    use rocketchat::e2e::{PrivateKeyEnvelope, RoomKey, UserPrivateKey};
    let f = fixture("webcrypto_interop.json");
    let s = |k: &str| f[k].as_str().unwrap().to_owned();
    // WebCrypto decrypted the key Rustket wrapped.
    assert_eq!(s("node_unwrapped_rust_wrapped"), s("room_key"));
    let private = UserPrivateKey::from_jwk_str(&s("private_key")).unwrap();
    let key = RoomKey::unwrap(&private, &s("node_wrapped")).unwrap();
    assert_eq!(key.kid, s("room_kid"));
    assert_eq!(*key.to_jwk_string(), s("room_key"));
    let msg = EncryptedContent::from_value(&f["node_message"]).unwrap();
    assert_eq!(key.decrypt_json(&msg).unwrap()["msg"], "from webcrypto ✓");
    let backup = PrivateKeyEnvelope::parse(&s("node_backup"), "ignored").unwrap();
    assert_eq!(
        *backup.decrypt(&s("node_backup_password")).unwrap(),
        s("private_key")
    );
}
