set_setting Accounts_PasswordReset false
set_setting Accounts_AllowPasswordChange false
set_setting Accounts_AllowUsernameChange false
set_setting Accounts_AllowEmailChange false
set_setting Accounts_AllowDeleteOwnAccount "$REVIEW_ALLOW_DELETE_OWN_ACCOUNT"
set_setting Accounts_Send_Email_When_Activating false
set_setting Accounts_Send_Email_When_Deactivating false
# Failed-login blocking by client address only: the review usernames are in
# this public repo, so blocking by user would let anyone lock them out.
set_setting Block_Multiple_Failed_Logins_Enabled true
set_setting Block_Multiple_Failed_Logins_By_Ip true
set_setting Block_Multiple_Failed_Logins_By_User false

# No external identity providers.
set_setting LDAP_Enable false
set_setting SAML_Custom_Default false
set_setting CAS_enabled false
for p in Apple Google Github Gitlab Facebook Twitter Linkedin Meteor Nextcloud Dolphin Drupal Wordpress; do
  set_setting "Accounts_OAuth_$p" false
done

# Content moderation.
set_setting Message_AllowBadWordsFilter true
set_setting Message_BadWordsFilterList "$(jstr "$REVIEW_BAD_WORDS")"

# Omnichannel: manual routing, so a queued visitor chat waits for the agent.
set_setting Livechat_enabled true
set_setting Livechat_Routing_Method '"Manual_Selection"'
set_setting Livechat_accept_chats_with_no_agents true
set_setting Livechat_title '"Quillmoor Labs Support"'

set_setting E2E_Enable "$REVIEW_E2E"
set_setting E2E_Enabled_Default_DirectRooms false
set_setting E2E_Enabled_Default_PrivateRooms false

set_setting FileUpload_Enabled true
set_setting FileUpload_MaxFileSize "$REVIEW_MAX_UPLOAD_BYTES"

# --- permissions: the moderation console stays with the admin role ----------

perms=$(as ops GET permissions.listAll)
for perm in view-moderation-console manage-moderation-actions; do
  body=$(python3 -I -c '
import json, sys
perm = sys.argv[1]
d = json.loads(sys.stdin.read())
for p in d.get("update", []):
    if p["_id"] == perm:
        if "admin" not in p.get("roles", []):
            print(json.dumps({"permissions": [{"_id": perm, "roles": p.get("roles", []) + ["admin"]}]}))
        break
' "$perm" <<<"$perms")
  if [[ -n "$body" ]]; then
    if ok "$(as ops POST permissions.update "$body")"; then log "permission $perm granted to admin"; else
      log "warning: could not update permission $perm"
      FAILED=1
    fi
  fi
done

# --- accounts ----------------------------------------------------------------

# ensure_user USER PASSWORD NAME ROLES_JSON
ensure_user() {
  local user=$1 pass=$2 name=$3 roles=$4 info r uid update=()
  info=$(as ops GET "users.info?username=$user")
  if ! ok "$info"; then
    r=$(as ops POST users.create "$(jb username="$user" email="$user@quillmoor.example" password="$pass" \
      name="$name" verified:=true requirePasswordChange:=false joinDefaultChannels:=true \
      sendWelcomeEmail:=false roles:="$roles")")
    ok "$r" || die "creating $user failed: $(jget 'd.get("error")' <<<"$r")"
    log "created $user (password $(mask "$pass"))"
    return
  fi
  uid=$(jget 'd["user"]["_id"]' <<<"$info")
  if [[ "$(jget 'd["user"].get("active")' <<<"$info")" != true ]]; then
    update+=(active:=true)
  fi
  if [[ "$(jget 'sorted(d["user"].get("roles", []))' <<<"$info")" != "$(jget 'sorted(d)' <<<"$roles")" ]]; then
    update+=(roles:="$roles")
  fi
  # Only reset the password when it no longer works, so reruns keep sessions.
  if [[ ${#update[@]} -eq 0 ]] && login probe "$user" "$pass"; then
    logout probe
  else
    update+=(password="$pass" requirePasswordChange:=false verified:=true)
  fi
  if [[ ${#update[@]} -gt 0 ]]; then
    r=$(as ops POST users.update "$(jb userId="$uid" data:="$(jb "${update[@]}")")")
    ok "$r" || die "updating $user failed: $(jget 'd.get("error")' <<<"$r")"
    log "updated $user"
  fi
}

ensure_user "${CRED[REVIEWER_USER]}" "${CRED[REVIEWER_PASSWORD]}" "App Reviewer" '["user"]'
ensure_user "${CRED[REVIEW_ADMIN_USER]}" "${CRED[REVIEW_ADMIN_PASSWORD]}" "Review Admin" '["admin","user"]'
ensure_user "${CRED[AGENT_USER]}" "${CRED[AGENT_PASSWORD]}" "Review Agent" '["livechat-agent","user"]'

is_agent() {
  as ops GET "livechat/users/agent?count=100" | python3 -I -c '
import json, sys
d = json.load(sys.stdin)
sys.exit(0 if any(u.get("username") == sys.argv[1] for u in d.get("users", [])) else 1)
' "$1"
}
if ! is_agent "${CRED[AGENT_USER]}"; then
  ok "$(as ops POST livechat/users/agent "$(jb username="${CRED[AGENT_USER]}")")" ||
    die "making ${CRED[AGENT_USER]} an omnichannel agent failed"
  log "${CRED[AGENT_USER]} is an omnichannel agent"
fi
if login agent "${CRED[AGENT_USER]}" "${CRED[AGENT_PASSWORD]}"; then
  as agent POST livechat/agent.status '{"status":"available"}' >/dev/null
  logout agent
fi

# --- review notes ------------------------------------------------------------

NOTES=$KIT_DIR/review-notes.txt
e2e_line="end-to-end"$'\n'"encrypted rooms (room \"$E2E_ROOM\"), "
e2e_account=$'\n'"- End-to-end encryption password of the regular user (asked for on a new Mac):"$'\n'"  ${CRED[REVIEWER_E2E_PASSWORD]}"
if [[ "$REVIEW_E2E" != true ]]; then
  e2e_line=""
  e2e_account=""
fi
(
  umask 077
  cat >"$NOTES" <<NOTES_EOF
