#!/usr/bin/env bash
# Brings up the review workspace and configures it. Idempotent: rerun it any
# time (outside a review) to heal settings, accounts and passwords.
#
#   ./setup.sh           generate credentials, docker compose up -d, configure
#   ./setup.sh --no-up   configure only (the stack is already running)
#
# Writes credentials.env and review-notes.txt next to this script (chmod 600,
# git-ignored). Passwords are never printed in full.
set -euo pipefail

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

UP=1
for arg in "$@"; do
  case $arg in
    --no-up) UP=0 ;;
    -h | --help)
      sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *) die "unknown argument: $arg" ;;
  esac
done

command -v curl >/dev/null || die "curl is required"
command -v python3 >/dev/null || die "python3 is required"
load_config
((UP == 0)) || check_compose_file

REVIEW_E2E=${REVIEW_E2E:-true}
REVIEW_MAX_UPLOAD_BYTES=${REVIEW_MAX_UPLOAD_BYTES:-5242880}
REVIEW_ALLOW_DELETE_OWN_ACCOUNT=${REVIEW_ALLOW_DELETE_OWN_ACCOUNT:-false}
REVIEW_BAD_WORDS=${REVIEW_BAD_WORDS:-fuck,fucking,shit,bullshit,bitch,bastard,asshole,cunt,dick,slut,whore,retard}
REVIEW_SUPPORT_EMAIL=${REVIEW_SUPPORT_EMAIL:-<support email>}
[[ "$REVIEW_E2E" == true || "$REVIEW_E2E" == false ]] || die "REVIEW_E2E must be true or false"
[[ "$REVIEW_ALLOW_DELETE_OWN_ACCOUNT" == true || "$REVIEW_ALLOW_DELETE_OWN_ACCOUNT" == false ]] ||
  die "REVIEW_ALLOW_DELETE_OWN_ACCOUNT must be true or false"
[[ "$REVIEW_MAX_UPLOAD_BYTES" =~ ^[0-9]+$ ]] || die "REVIEW_MAX_UPLOAD_BYTES must be a number"

# --- credentials -------------------------------------------------------------

ensure_credentials() {
  load_credentials
  local changed=0 k
  local -A defaults=(
    [OPS_ADMIN_USER]=rustket-ops
    [REVIEWER_USER]=reviewer
    [REVIEW_ADMIN_USER]=review-admin
    [AGENT_USER]=review-agent
  )
  for k in OPS_ADMIN_USER REVIEWER_USER REVIEW_ADMIN_USER AGENT_USER; do
    [[ -n "${CRED[$k]:-}" ]] || { CRED[$k]=${defaults[$k]}; changed=1; }
  done
  for k in OPS_ADMIN_PASSWORD REVIEWER_PASSWORD REVIEW_ADMIN_PASSWORD AGENT_PASSWORD SEED_PASSWORD; do
    [[ -n "${CRED[$k]:-}" ]] || { CRED[$k]=$(gen_password); changed=1; }
  done
  # Set by hand in Rustket (README.md, "E2E"); Rustket wants 30+ characters.
  [[ -n "${CRED[REVIEWER_E2E_PASSWORD]:-}" ]] || { CRED[REVIEWER_E2E_PASSWORD]=$(gen_password 7); changed=1; }
  # The seeded omnichannel visitor; random so nobody else can post as it.
  [[ -n "${CRED[VISITOR_TOKEN]:-}" ]] || {
    CRED[VISITOR_TOKEN]=$(python3 -I -c 'import secrets; print(secrets.token_hex(16))')
    changed=1
  }
  if ((changed)); then
    (
      umask 077
      {
        echo "# Review server accounts, generated by setup.sh. Keep private; never commit."
        echo "# OPS_ADMIN is the operator account for these scripts: do not give it to App Review."
        for k in OPS_ADMIN_USER OPS_ADMIN_PASSWORD REVIEWER_USER REVIEWER_PASSWORD \
          REVIEW_ADMIN_USER REVIEW_ADMIN_PASSWORD AGENT_USER AGENT_PASSWORD SEED_PASSWORD \
          REVIEWER_E2E_PASSWORD VISITOR_TOKEN; do
          printf '%s=%s\n' "$k" "${CRED[$k]}"
        done
      } >"$CREDENTIALS_FILE.tmp"
      mv "$CREDENTIALS_FILE.tmp" "$CREDENTIALS_FILE"
    )
    log "wrote $CREDENTIALS_FILE"
  fi
  chmod 600 "$CREDENTIALS_FILE"
}

# Rocket.Chat creates this admin on its very first start (empty database only).
write_admin_env() {
  local file=$KIT_DIR/admin.env content
  content=$(printf 'ADMIN_USERNAME=%s\nADMIN_PASS=%s\nADMIN_EMAIL=%s\nADMIN_NAME=%s\n' \
    "${CRED[OPS_ADMIN_USER]}" "${CRED[OPS_ADMIN_PASSWORD]}" "ops@example.invalid" "Operator")
  # Rewriting an unchanged file would still be harmless, but keep mtime stable.
  if [[ -f "$file" ]] && [[ "$(cat "$file")" == "$content" ]]; then
    chmod 600 "$file"
    return
  fi
  (
    umask 077
    printf '%s\n' "$content" >"$file"
  )
  chmod 600 "$file"
  log "wrote $file"
}

ensure_credentials
write_admin_env

if ((UP)); then
  [[ -f "$KIT_DIR/.env" ]] || die "$KIT_DIR/.env is missing (copy .env.example)"
  command -v docker >/dev/null || die "docker is required"
  log "docker compose up -d ($REVIEW_PROXY mode)"
  compose up -d
fi

if [[ "$REVIEW_PROXY" == tunnel ]] && command -v systemctl >/dev/null &&
  ! systemctl --user is-active --quiet "$REVIEW_TUNNEL_NAME.service"; then
  log "warning: $REVIEW_TUNNEL_NAME.service is not running; run ./tunnel.sh first"
fi

wait_for_server

# The admin is created shortly after the HTTP server starts.
for i in $(seq 1 24); do
  login ops "${CRED[OPS_ADMIN_USER]}" "${CRED[OPS_ADMIN_PASSWORD]}" operator && break
  ((i == 24)) && login_operator
  sleep 5
done
log "logged in as ${CRED[OPS_ADMIN_USER]}"

# --- settings ----------------------------------------------------------------

FAILED=0
jstr() { python3 -I -c 'import json,sys; print(json.dumps(sys.argv[1]))' "$1"; }

same_value() {
  python3 -I -c '
import json, sys
try:
    cur = json.loads(sys.argv[1]).get("value")
except Exception:
    sys.exit(1)
sys.exit(0 if cur == json.loads(sys.argv[2]) else 1)
' "$1" "$2"
}

# set_setting ID JSON_VALUE: writes only when the value differs.
set_setting() {
  local id=$1 want=$2 cur r
  cur=$(as ops GET "settings/$id")
  if ! ok "$cur"; then
    log "warning: setting $id does not exist on this server"
    FAILED=1
    return
  fi
  same_value "$cur" "$want" && return
  r=$(as ops POST "settings/$id" "{\"value\":$want}")
  if ok "$r"; then
    log "setting $id updated"
  else
    log "warning: setting $id: $(jget 'd.get("error")' <<<"$r")"
    FAILED=1
  fi
}

log "applying settings"
set_setting Site_Name '"Rustket Review"'

# Accounts: no self-registration, password login only, nothing that needs mail
# (no SMTP here) and nothing a reviewer could use to lock a shared account.
set_setting Accounts_RegistrationForm '"Disabled"'
set_setting Accounts_Registration_AuthenticationServices_Enabled false
set_setting Accounts_ShowFormLogin true
set_setting Accounts_AllowAnonymousRead false
set_setting Accounts_TwoFactorAuthentication_By_Email_Auto_Opt_In false
set_setting Accounts_TwoFactorAuthentication_By_Email_Enabled false
