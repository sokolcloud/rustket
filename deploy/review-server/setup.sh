  regular user   ${CRED[REVIEWER_USER]}  $(mask "${CRED[REVIEWER_PASSWORD]}")
  admin          ${CRED[REVIEW_ADMIN_USER]}  $(mask "${CRED[REVIEW_ADMIN_PASSWORD]}")
